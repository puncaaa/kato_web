def run_import():
    print(f"Source directory: {SOURCE_DIR}")
    print(f"Target media directory: {MEDIA_PROGRAMS_DIR}")
    
    # 1. Copy files
    for item in CONFERENCES_DATA:
        src = os.path.join(SOURCE_DIR, item["src_file"])
        dst = os.path.join(MEDIA_PROGRAMS_DIR, item["target_file"])
        if os.path.exists(src):
            shutil.copy2(src, dst)
            print(f"[COPIED] {item['src_file']} -> {item['target_file']}")
        else:
            print(f"[WARNING] Source file not found: {src}")

    # Copy the doc file as well if present
